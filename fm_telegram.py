class Doorbell:
    """Wake the Firstmate primary without putting untrusted note text in a pane."""
    def __init__(self, home: Path, enabled: bool, logger: logging.Logger,
                 runner: Callable[..., Any] = subprocess.run,
                 clock: Callable[[], float] = time.monotonic,
                 agent: Optional[str] = None) -> None:
        self.home, self.enabled, self.log, self.agent = home, enabled, logger, agent
        self._runner, self._clock = runner, clock
        self._last_ring: Optional[float] = None
        self._pending_id: Optional[str] = None

    def queue(self, note_id: str) -> None:
        if not self.enabled:
            return
        now = self._clock()
        if self._last_ring is None or now - self._last_ring >= DOORBELL_COOLDOWN_SECONDS:
            self._ring(note_id, now)
        else:
            self._pending_id = note_id

    def flush(self) -> None:
        if not self.enabled or self._pending_id is None or self._last_ring is None:
            return
        now = self._clock()
        if now - self._last_ring >= DOORBELL_COOLDOWN_SECONDS:
            note_id, self._pending_id = self._pending_id, None
            self._ring(note_id, now)

    def _ring(self, note_id: str, now: float) -> None:
        # Count even a failed attempt toward the cooldown; durable inbox delivery
        # remains the fallback and retrying every poll would make failure noisy.
        self._last_ring = now
        if not NOTE_ID.fullmatch(note_id):
            # The id is typed into an agent's terminal, so accept only plain id characters.
            self.log.warning("doorbell skipped: unexpected note id format")
            return
        line = "[telegram] new captain note %s in fm-inbox — drain and reply" % note_id
        try:
            listed = self._runner(["herdr", "pane", "list"], text=True,
                                  stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
            payload = json.loads(listed.stdout)
            panes = payload["result"]["panes"]
            # Any agent pane in the Firstmate home unless doorbell_agent names one.
            pane = next((item for item in panes if item.get("agent")
                         and (self.agent is None or item.get("agent") == self.agent)
                         and item.get("cwd") == str(self.home)), None)
            if not pane:
                raise RuntimeError("no matching Firstmate pane")
            pane_id = pane.get("pane_id", pane.get("id", pane.get("pane")))
            if not isinstance(pane_id, str):
                raise RuntimeError("matching pane has no id")
            self._runner(["herdr", "pane", "send-text", pane_id, line], text=True,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
            self._runner(["herdr", "pane", "send-keys", pane_id, "Enter"], text=True,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
        except (OSError, subprocess.SubprocessError, ValueError, TypeError, RuntimeError,
                AttributeError, KeyError):
            self.log.warning("doorbell unavailable for note id=%s", note_id)


class Bridge:
    def __init__(self, api: Any, inbox: Any, state: State, owner_chat_id: int,
                 redactor: Redactor, logger: logging.Logger,
                 doorbell: Optional[Doorbell] = None,
                 transcriber: Optional[Callable[[Path], str]] = None,
                 transcript_prefixes: Iterable[str] = ()) -> None:
        self.api, self.inbox, self.state = api, inbox, state
        self.owner_chat_id, self.redactor, self.log = owner_chat_id, redactor, logger
        self.stopping = False
        self._last_send = 0.0
        self.doorbell = doorbell
        self.transcriber = transcriber
        self.transcript_prefixes = list(transcript_prefixes)

    def send(self, text: str) -> None:
        if len(text) > MAX_OUTBOUND_CHARS:
            text = text[:MAX_OUTBOUND_CHARS] + "\n… (truncated)"
        redacted = self.redactor.redact(text)
        if not redacted:
            return
        formatted = markdown_to_telegram_html(redacted)
        for part in split_telegram_html(formatted):
            # Telegram permits considerably more than this, but a modest local cap
            # keeps a long reply from becoming a burst of outbound API requests.
            remaining = 0.05 - (time.monotonic() - self._last_send)
            if remaining > 0:
                time.sleep(remaining)
            try:
                self.api.send(self.owner_chat_id, part, parse_mode="HTML")
            except TelegramAPIError:
                # A malformed entity must not swallow a captain-facing result.
                self.api.send(self.owner_chat_id, _plain_html(part))
            self._last_send = time.monotonic()

    def process_update(self, update: dict[str, Any]) -> None:
        update_id = update.get("update_id")
        if not isinstance(update_id, int):
            return
        message = update.get("message") or {}
        chat_id = (message.get("chat") or {}).get("id")
        if chat_id != self.owner_chat_id:
            if isinstance(chat_id, int):
                self.log.warning("ignored Telegram message from chat id=%d", chat_id)
            return
        if update_id in self.state.data.get("handled_update_ids", []):
            return  # A replayed update: no second download, transcription or receipt.
        text = message.get("text")
        if not isinstance(text, str):
            try:
                text = self._attachment_text(update_id, message)
                reason = None if text is not None else "unsupported type"
            except AttachmentTooLarge:
                reason = "over 20 MB"
            if reason:
                # Never drop silently: Firstmate still learns what arrived.
                caption = message.get("caption")
                note = "(attachment not received: %s — %s)" % (self._describe(message), reason)
                if isinstance(caption, str) and caption.strip():
                    note += "\n" + caption
                self._submit(update_id, note, "Could not save that (%s). Only the fact that it "
                             "arrived was sent as note %%s." % reason)
                return
            self._submit(update_id, text)
            return
        command = text.strip().split(maxsplit=1)[0].split("@", 1)[0]
        if command == "/help":
            self.send("Send text, photos, voice, video or files (up to 20 MB) and each becomes a "
                      "Firstmate note. /status shows the inbox status. Keep secrets, logs and "
                      "diffs out of Telegram; read them on the machine itself.")
            return
        if command == "/status":
            self.send(self.inbox.status()[:3500] or "No status available.")
            return
        self._submit(update_id, text)

    def _attachment_text(self, update_id: int, message: dict[str, Any]) -> Optional[str]:
        """Download a photo, voice/audio/video or any document; None means unsupported."""
        photos = message.get("photo")
        document = message.get("document")
        voice_kind = next((kind for kind in VOICE_KINDS if isinstance(message.get(kind), dict)), None)
        if voice_kind:
            item = message[voice_kind]
            mime = str(item.get("mime_type") or VOICE_KINDS[voice_kind])
        elif isinstance(photos, list) and photos:
            item = max(photos, key=lambda size: size.get("file_size") or
                       (size.get("width") or 0) * (size.get("height") or 0))
            mime = "image/jpeg"
        elif isinstance(document, dict):
            item, mime = document, str(document.get("mime_type") or "application/octet-stream")
        else:
            return None
        file_id, unique_id = item.get("file_id"), str(item.get("file_unique_id") or "")
        if not isinstance(file_id, str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", unique_id):
            return None
        if int(item.get("file_size") or 0) > MAX_ATTACHMENT_BYTES:
            raise AttachmentTooLarge()
        remote_path, data = self.api.get_file(file_id, MAX_ATTACHMENT_BYTES)
        extension = Path(remote_path).suffix.lstrip(".").lower()
        if not re.fullmatch(r"[a-z0-9]{1,8}", extension):
            extension = (mimetypes.guess_extension(mime) or ".bin").lstrip(".")
        media = self.state.directory / "media"
        media.mkdir(mode=0o700, exist_ok=True)
        os.chmod(media, 0o700)
        # Keep the sender's file name: last path component only, separators and other
        # punctuation replaced, bounded so multi-byte names stay under the 255-byte limit.
        original = Path(str(item.get("file_name") or ""))
        stem = re.sub(r"[^\w.-]+", "_", original.stem)[:50].strip("._")
        extension = re.sub(r"\W+", "", original.suffix)[:9].lower() or extension
        target = media / ("%d-%s%s.%s" % (update_id, unique_id, "-" + stem if stem else "", extension))
        descriptor = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
        os.chmod(target, 0o600)
        caption = message.get("caption")
        if voice_kind:
            try:
                transcript = self.transcriber(target).strip() if self.transcriber else ""
            except (OSError, subprocess.SubprocessError) as exc:
                # filename names the missing binary on FileNotFoundError; never message text.
                self.log.warning("voice transcription failed for update id=%d: %s%s", update_id,
                                 type(exc).__name__, " (%s)" % exc.filename
                                 if getattr(exc, "filename", None) else "")
                transcript = ""
            # Whisper renders a spoken colon as a comma ("todo, buy milk"); restore it for the
            # configured prefixes so a spoken "todo: ..." reads exactly like a typed one.
            for prefix in self.transcript_prefixes:
                transcript = re.sub(r"^%s(?:\s*[,.:]|\s)\s*" % re.escape(prefix),
                                    lambda _match: prefix + ": ", transcript)
            body = transcript or "(transcription failed — check the attached audio)"
            if isinstance(caption, str) and caption.strip():
                body = "%s\n%s" % (body, caption)
            return "%s\n(voice)\nattachment: %s" % (body, target.resolve())
        placeholder = "(photo)" if mime.startswith("image/") else "(file)"
        caption = caption if isinstance(caption, str) and caption.strip() else placeholder
        return "%s\nattachment: %s" % (caption, target.resolve())

    @staticmethod
    def _describe(message: dict[str, Any]) -> str:
        """Summarise an attachment by kind, file name and size, never by content."""
        kind = next((key for key, value in message.items()
                     if isinstance(value, (dict, list)) and key not in MESSAGE_CONTEXT), "unknown")
        item = message.get(kind)
        item = item[-1] if isinstance(item, list) and item else item
        item = item if isinstance(item, dict) else {}
        parts = [kind]
        if isinstance(item.get("file_name"), str):
            parts.append("name=%s" % item["file_name"])
        if isinstance(item.get("file_size"), int):
            parts.append("size=%sKB" % format(round(item["file_size"] / 1024), ","))
        return ", ".join(parts)

    def _submit(self, update_id: int, text: str, receipt: str = "Received. Note ID: %s") -> None:
        note = self.inbox.note("tg:%d" % update_id, text)
        if isinstance(note, str):  # Compatibility with an Inbox test double.
            note = Note(note)
        note_id = note.id
        handled = self.state.data.setdefault("handled_update_ids", [])
        handled[:] = (handled + [update_id])[-MAX_HANDLED_UPDATES:]
        self.state.save()
        known = self.state.data.setdefault("telegram_note_ids", [])
        if note_id not in known:
            known.append(note_id)
            if note.created and self.doorbell:
                self.doorbell.queue(note_id)
        self.send(receipt % note_id)

    def check_replies(self) -> None:
        receipts = self.inbox.receipts(str(self.state.data.get("receipt_cursor", "")))
        known = set(self.state.data.get("telegram_note_ids", []))
        cursor = str(self.state.data.get("receipt_cursor", ""))
        for reply in receipts.get("replies", []):
            reply_cursor = str(reply.get("cursor", ""))
            if reply.get("id") in known:
                self.send(str(reply.get("body", "")))
            # All receipts are consumed to avoid permanent re-polling of unrelated replies.
            cursor = reply_cursor or cursor
            self.state.data["receipt_cursor"] = cursor
            self.state.save()
        if not receipts.get("replies") and receipts.get("reply_cursor"):
            self.state.data["receipt_cursor"] = str(receipts["reply_cursor"])
            self.state.save()

    def once(self) -> None:
        offset = int(self.state.data.get("offset", 0))
        for update in self.api.updates(offset):
            self.process_update(update)
            self.state.data["offset"] = int(update["update_id"]) + 1
            self.state.save()
        if self.doorbell:
            self.doorbell.flush()
        self.check_replies()

    def run(self, interval: float) -> None:
        delay = 1.0
        while not self.stopping:
            try:
                self.once()
                delay = 1.0
                if not self.stopping:
                    time.sleep(interval)
            except (RuntimeError, OSError) as exc:
                self.log.warning("bridge operation failed: %s", self.redactor.redact(str(exc)))
                time.sleep(delay)
                delay = min(delay * 2, 60.0)


def logger_for(redactor: Redactor) -> logging.Logger:
    class SafeFormatter(logging.Formatter):
        def format(self, record: logging.LogRecord) -> str:
            return redactor.redact(super().format(record))
    logger = logging.getLogger("fm-telegram")
    logger.setLevel(logging.INFO)
    handler = logging.StreamHandler()
    handler.setFormatter(SafeFormatter("%(asctime)s %(levelname)s %(message)s"))
    logger.handlers[:] = [handler]
    return logger


def _path(value: Any) -> Optional[Path]:
    return Path(str(value)).expanduser() if value else None


def build_bridge(args: argparse.Namespace) -> tuple[Bridge, dict[str, Any]]:
    config = load_config(args.config, args.state_dir / "config.json")
    home = args.home or _path(config["firstmate_home"])
    if not home:
        raise RuntimeError("set firstmate_home in the config (or FM_HOME / --home)")
    state = State(args.state_dir)
    token = read_token(str(config["keychain_service"]))
    redactor = Redactor(_path(config["denylist_file"]), secrets=[token])
    logger = logger_for(redactor)
    doorbell = Doorbell(home, bool(config["doorbell"]), logger, agent=config["doorbell_agent"])
    whisper = str(config["whisper_cli"] or shutil.which("whisper-cli") or "whisper-cli")
    model, language = _path(config["whisper_model"]), str(config["whisper_language"])
    bridge = Bridge(TelegramAPI(token, base=config["api_base"]), Inbox(home), state,
                    config["owner_chat_id"], redactor, logger, doorbell,
                    transcriber=lambda path: transcribe(path, whisper, model, language),
                    transcript_prefixes=config["transcript_prefixes"])
    return bridge, config


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path,
                        default=_path(os.environ.get("FM_TELEGRAM_CONFIG")) or DEFAULT_CONFIG)
    parser.add_argument("--home", type=Path, default=_path(os.environ.get("FM_HOME")))
    parser.add_argument("--state-dir", type=Path,
                        default=_path(os.environ.get("FM_TELEGRAM_STATE_DIR")) or DEFAULT_STATE)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("run")
    notify = sub.add_parser("notify", help="send a redacted captain-facing notification")
    notify.add_argument("text", help="notification text, or - to read stdin")
    args = parser.parse_args(argv)
    bridge, config = build_bridge(args)
    if args.command == "notify":
        bridge.send(sys.stdin.read() if args.text == "-" else args.text)
        return 0
    def stop(_signum: int, _frame: Any) -> None:
        bridge.stopping = True
    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    bridge.run(float(config["poll_interval_seconds"]))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # Never interpolate process/HTTP details that could contain token.
        print("fm-telegram: " + Redactor().redact(str(exc)), file=sys.stderr)
        raise SystemExit(1)

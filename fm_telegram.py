def _tag_name(tag: str) -> Optional[str]:
    match = re.match(r"</?([A-Za-z][A-Za-z0-9-]*)", tag)
    return match.group(1).lower() if match else None


def _plain_html(value: str) -> str:
    """Convert HTML generated by this module to a safe fallback message."""
    return html.unescape(HTML_TAG.sub("", value))


def _valid_link(url: str) -> bool:
    parsed = urlparse(url)
    return parsed.scheme in {"http", "https", "tg"} and bool(parsed.netloc or parsed.scheme == "tg")


def _inline_html(value: str) -> str:
    """Render the small Markdown subset produced by Firstmate, escaping all else."""
    saved: list[str] = []

    def save(rendered: str) -> str:
        marker = "\x00TG%d\x00" % len(saved)
        saved.append(rendered)
        return marker

    def code(match: re.Match[str]) -> str:
        return save("<code>%s</code>" % html.escape(match.group(1)))

    def link(match: re.Match[str]) -> str:
        label, url = match.group(1), match.group(2).strip()
        if not _valid_link(url):
            return match.group(0)
        return save('<a href="%s">%s</a>' % (html.escape(url, quote=True), html.escape(label)))

    # Protect literal code and URLs before escaping or interpreting emphasis.
    value = re.sub(r"`([^`\n]+)`", code, value)
    value = re.sub(r"\[([^\]\n]+)\]\(([^)\s]+)\)", link, value)
    value = html.escape(value)
    # The deliberate ordering makes bold markers disappear before italic markers.
    value = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", value)
    value = re.sub(r"__(.+?)__", r"<b>\1</b>", value)
    value = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"<i>\1</i>", value)
    value = re.sub(r"(?<!\w)_([^_\n]+)_(?!\w)", r"<i>\1</i>", value)
    for index, rendered in enumerate(saved):
        value = value.replace("\x00TG%d\x00" % index, rendered)
    return value


def _table_cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def markdown_to_telegram_html(text: str) -> str:
    """Render Markdown-ish reply text as the safe HTML subset accepted by Telegram."""
    lines = text.splitlines()
    output: list[str] = []
    index = 0
    in_fence = False
    language = ""
    code_lines: list[str] = []

    def finish_code() -> None:
        nonlocal code_lines, language
        body = html.escape("\n".join(code_lines))
        if language:
            output.append('<pre><code class="language-%s">%s</code></pre>' % (language, body))
        else:
            output.append("<pre>%s</pre>" % body)
        code_lines, language = [], ""

    while index < len(lines):
        line = lines[index]
        fence = FENCE.match(line)
        if fence:
            if in_fence:
                finish_code()
                in_fence = False
            else:
                in_fence, language = True, fence.group(1)
            index += 1
            continue
        if in_fence:
            code_lines.append(line)
            index += 1
            continue
        if index + 1 < len(lines) and "|" in line and TABLE_DIVIDER.match(lines[index + 1]):
            headers = _table_cells(line)
            index += 2
            while index < len(lines) and "|" in lines[index] and lines[index].strip():
                cells = _table_cells(lines[index])
                if len(cells) >= 2:
                    pairs = ["%s: %s" % (_inline_html(header), _inline_html(cell))
                             for header, cell in zip(headers, cells)]
                    output.append("• " + " · ".join(pairs))
                index += 1
            continue
        item = LIST_ITEM.match(line)
        if item:
            # Preserve nesting visually without unsupported HTML list tags.
            output.append("%s• %s" % (item.group(1), _inline_html(item.group(2))))
        elif line.startswith("#") and re.match(r"^#{1,6}\s+", line):
            output.append("<b>%s</b>" % _inline_html(re.sub(r"^#{1,6}\s+", "", line)))
        else:
            output.append(_inline_html(line))
        index += 1
    if in_fence:
        finish_code()
    return "\n".join(output)


def _safe_text_cut(value: str, maximum: int) -> int:
    """Prefer paragraph/line/word boundaries and never split an HTML entity."""
    if len(value) <= maximum:
        return len(value)
    candidates = (value.rfind("\n\n", 0, maximum + 1), value.rfind("\n", 0, maximum + 1),
                  value.rfind(" ", 0, maximum + 1))
    cut = next((point + (2 if point == candidates[0] else 1)
                for point in candidates if point > 0), maximum)
    ampersand = value.rfind("&", 0, cut)
    if ampersand >= 0 and ";" not in value[ampersand:cut]:
        cut = ampersand
    return cut


def split_telegram_html(value: str, limit: int = TELEGRAM_LIMIT) -> list[str]:
    """Split generated Telegram HTML without breaking a tag or leaving it unbalanced."""
    if limit < 32:
        raise ValueError("Telegram HTML limit is too small")
    tokens = re.split(r"(<[^>]+>)", value)
    result: list[str] = []
    open_tags: list[tuple[str, str]] = []
    prefix = ""
    current = ""

    def closers() -> str:
        return "".join("</%s>" % name for name, _tag in reversed(open_tags))

    def flush() -> None:
        nonlocal prefix, current
        if current:
            result.append(prefix + current + closers())
        prefix = "".join(tag for _name, tag in open_tags)
        current = ""

    for token in tokens:
        if not token:
            continue
        if token.startswith("<"):
            name = _tag_name(token)
            if token.startswith("</"):
                if len(prefix) + len(current) + len(token) + len(closers()) <= limit:
                    current += token
                else:
                    flush()
                    current += token
                if name and open_tags and open_tags[-1][0] == name:
                    open_tags.pop()
            else:
                if len(prefix) + len(current) + len(token) + len(closers()) > limit:
                    flush()
                current += token
                if name and not token.endswith("/>"):
                    open_tags.append((name, token))
            continue
        while token:
            space = limit - len(prefix) - len(current) - len(closers())
            if space <= 0:
                flush()
                continue
            cut = _safe_text_cut(token, space)
            if cut == 0:
                flush()
                continue
            current += token[:cut]
            token = token[cut:]
            if token:
                flush()
    flush()
    return result


class Redactor:
    def __init__(self, denylist: Optional[Path] = None, secrets: Iterable[str] = ()) -> None:
        # Literal secrets (the bot token itself) are redacted even if no pattern matches them.
        self.terms: list[str] = [secret for secret in secrets if secret]
        if denylist and denylist.is_file():
            self.terms += [line.strip() for line in denylist.read_text(encoding="utf-8").splitlines()
                           if line.strip() and not line.lstrip().startswith("#")]

    def redact(self, value: str) -> str:
        for pattern in TOKEN_PATTERNS:
            value = pattern.sub("[redacted]", value)
        for term in self.terms:
            value = value.replace(term, "[redacted]")
        return value


def chunks(text: str, limit: int = TELEGRAM_LIMIT) -> Iterable[str]:
    """Split conservatively, preferring newlines and never emitting an oversize chunk."""
    while len(text) > limit:
        cut = text.rfind("\n", 0, limit + 1)
        if cut <= 0:
            cut = text.rfind(" ", 0, limit + 1)
        if cut <= 0:
            cut = limit
        yield text[:cut]
        text = text[cut:]
        if text.startswith("\n") or text.startswith(" "):
            text = text[1:]
    if text:
        yield text


def transcribe(path: Path, whisper: str, model: Path, language: str = "auto") -> str:
    """Transcribe audio locally with afconvert + whisper.cpp; nothing leaves the machine."""
    with tempfile.TemporaryDirectory(prefix="fm-telegram-") as work:
        wav = Path(work) / "audio.wav"
        # Argument lists only: no shell, and both paths are generated by this module.
        subprocess.run([AFCONVERT, "-f", "WAVE", "-d", "LEI16@16000", "-c", "1", str(path), str(wav)],
                       check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
        result = subprocess.run([whisper, "-m", str(model), "-l", language, "-nt", "-np",
                                 "-f", str(wav)], check=True, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=180)
    return " ".join(line.strip() for line in result.stdout.splitlines() if line.strip())


def read_token(service: str) -> str:
    """Read the token from the environment or the macOS login Keychain; never persist it."""
    token = os.environ.get(TOKEN_ENV, "").strip()
    if token:
        return token
    try:
        result = subprocess.run(
            ["security", "find-generic-password", "-s", service,
             "-a", os.environ.get("USER", ""), "-w"],
            check=True, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError("no Telegram bot token: set %s or add Keychain item %r"
                           % (TOKEN_ENV, service)) from exc
    token = result.stdout.strip()
    if not token:
        raise RuntimeError("macOS Keychain returned an empty Telegram bot token")
    return token


def _check_api_base(url: str) -> str:
    """Only HTTPS may carry the token off the machine; plain HTTP is for local test servers."""
    parsed = urlparse(url)
    loopback = parsed.hostname in {"localhost", "127.0.0.1", "::1"}
    if parsed.scheme != "https" and not (parsed.scheme == "http" and loopback):
        raise RuntimeError("api_base must be https:// (http:// is allowed only for localhost)")
    return url.rstrip("/")


def parse_choices(values: Iterable[str]) -> list[dict[str, Any]]:
    """Parse repeated QUESTION:OPTION=label command-line choice specifications."""
    questions: dict[str, dict[str, Any]] = {}
    for value in values:
        match = CHOICE_SPEC.fullmatch(value)
        if not match:
            raise ValueError("choice must be QUESTION:OPTION=label")
        question_id, option_id, label = match.groups()
        label = label.strip()
        if not label or len(label) > 62:
            raise ValueError("choice labels must be 1 to 62 characters")
        question = questions.setdefault(question_id, {"id": question_id, "options": []})
        if any(option["id"] == option_id for option in question["options"]):
            raise ValueError("duplicate choice: %s:%s" % (question_id, option_id))
        question["options"].append({"id": option_id, "label": label})
    if not questions:
        raise ValueError("at least one --choice is required")
    return list(questions.values())


def _choice_question(text: str, question_id: str) -> str:
    """Keep the matching numbered prompt with a choice reply when practical."""
    pattern = re.compile(r"^\s*%s[).:]\s*(.+)$" % re.escape(question_id))
    for line in text.splitlines():
        match = pattern.match(line)
        if match:
            return match.group(1).strip()
    return "Question %s" % question_id


def load_config(path: Path, legacy: Optional[Path] = None) -> dict[str, Any]:
    """Load the user-owned JSON config; it chooses which fm-inbox.sh runs, so refuse loose modes."""
    if not path.exists() and legacy and legacy.exists():
        path = legacy  # Configs written by earlier versions lived in the state directory.
    try:
        info = path.stat()
        configured = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise RuntimeError("config not found: %s (see README, Configuration)" % path) from None
    except ValueError as exc:
        raise RuntimeError("config is not valid JSON: %s" % path) from exc
    if info.st_mode & 0o022 or info.st_uid != os.getuid():
        raise RuntimeError("config must be owned by you and not group/world writable: chmod 600 %s"
                           % path)
    if not isinstance(configured, dict):
        raise RuntimeError("config must be a JSON object: %s" % path)
    config = {**CONFIG_DEFAULTS, **configured}
    chat_id = config["owner_chat_id"]
    if isinstance(chat_id, bool) or not isinstance(chat_id, int):
        raise RuntimeError("config owner_chat_id must be your numeric Telegram chat id")
    config["api_base"] = _check_api_base(str(config["api_base"]))
    return config


class TelegramAPI:
    def __init__(self, token: str, opener: Callable[..., Any] = urlopen,
                 base: str = CONFIG_DEFAULTS["api_base"]) -> None:
        self._token = token
        self._opener = opener
        self._base = base

    def call(self, method: str, payload: dict[str, Any]) -> Any:
        # Token only appears in this transient URL, never in exceptions/log records.
        request = Request(
            "%s/bot%s/%s" % (self._base, self._token, method),
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}, method="POST",
        )
        try:
            with self._opener(request, timeout=40) as response:
                body = json.loads(response.read().decode("utf-8"))
        except HTTPError as exc:
            # Telegram reports rejections (bad entities, 401, 409, 429) as HTTP 4xx.
            exc.close()
            raise TelegramAPIError("Telegram API rejected request (HTTP %d)" % exc.code) from None
        except (URLError, OSError, ValueError) as exc:
            raise RuntimeError("Telegram network request failed") from exc
        if not body.get("ok"):
            raise TelegramAPIError("Telegram API rejected request")
        return body.get("result")

    def updates(self, offset: int) -> list[dict[str, Any]]:
        return self.call("getUpdates", {"offset": offset, "timeout": 30,
                                        "allowed_updates": ["message", "callback_query"]})

    def get_file(self, file_id: str, limit: int) -> tuple[str, bytes]:
        """Return Telegram's file_path and contents, refusing anything over limit bytes."""
        info = self.call("getFile", {"file_id": file_id}) or {}
        path = info.get("file_path")
        if not isinstance(path, str) or not path:
            raise RuntimeError("Telegram getFile returned no file path")
        if int(info.get("file_size") or 0) > limit:
            raise AttachmentTooLarge()
        request = Request("%s/file/bot%s/%s" % (self._base, self._token, path))
        try:
            with self._opener(request, timeout=40) as response:
                data = response.read(limit + 1)
        except (URLError, OSError) as exc:
            raise RuntimeError("Telegram file download failed") from exc
        if len(data) > limit:
            raise AttachmentTooLarge()
        return path, data

    def send(self, chat_id: int, text: str, parse_mode: Optional[str] = None,
             reply_markup: Optional[dict[str, Any]] = None) -> Any:
        payload: dict[str, Any] = {"chat_id": chat_id, "text": text,
                                   "disable_web_page_preview": True}
        if parse_mode:
            payload["parse_mode"] = parse_mode
        if reply_markup:
            payload["reply_markup"] = reply_markup
        return self.call("sendMessage", payload)

    def answer_callback(self, callback_id: str, text: Optional[str] = None) -> Any:
        payload: dict[str, Any] = {"callback_query_id": callback_id}
        if text:
            payload["text"] = text
        return self.call("answerCallbackQuery", payload)

    def edit_reply_markup(self, chat_id: int, message_id: int,
                          reply_markup: dict[str, Any]) -> Any:
        return self.call("editMessageReplyMarkup", {
            "chat_id": chat_id, "message_id": message_id, "reply_markup": reply_markup,
        })


class Inbox:
    def __init__(self, home: Path) -> None:
        self.home = home
        self.command = home / "bin/fm-inbox.sh"

    def _run(self, args: list[str], body: Optional[str] = None) -> str:
        environment = os.environ.copy()
        environment["FM_HOME"] = str(self.home)
        result = subprocess.run([str(self.command), *args], input=body, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                env=environment, check=False)
        if result.returncode not in (0, 3):
            raise RuntimeError("fm-inbox command failed")
        return result.stdout

    def note(self, request_id: str, text: str) -> "Note":
        output = self._run(["note", "--request-id", request_id, "--json", "-"], text)
        try:
            result = json.loads(output)
            note_id = str(result["id"])
        except (ValueError, KeyError, TypeError) as exc:
            raise RuntimeError("fm-inbox returned invalid note JSON") from exc
        # fm-inbox marks request-id replays explicitly.  Retain a conservative
        # default for older versions whose JSON only contained the note id.
        replayed = bool(result.get("replayed", result.get("duplicate", False)))
        if "replay" in (result.get("outcome"), result.get("status")) or \
                result.get("status") in ("replayed", "duplicate"):
            replayed = True
        if "created" in result:
            created = bool(result["created"])
        elif "new" in result:
            created = bool(result["new"])
        else:
            created = not replayed
        return Note(note_id, created=created)

    def status(self) -> str:
        # Status goes to Telegram, so local paths are shortened (README: no private paths).
        return self._run(["status"]).replace(str(self.home), "$FM_HOME").replace(str(Path.home()), "~")

    def receipts(self, cursor: str) -> dict[str, Any]:
        output = self._run(["receipts", "--after", cursor]) if cursor else self._run(["receipts"])
        try:
            return json.loads(output)
        except ValueError as exc:
            raise RuntimeError("fm-inbox returned invalid receipts JSON") from exc

    def pending(self) -> list[dict[str, Any]]:
        """Return pending notes through fm-inbox's public receipt interface."""
        output = self._run(["receipts", "--all-pending"])
        try:
            result = json.loads(output)
            pending = result.get("pending", [])
        except (ValueError, AttributeError) as exc:
            raise RuntimeError("fm-inbox returned invalid pending receipts JSON") from exc
        if not isinstance(pending, list):
            raise RuntimeError("fm-inbox returned invalid pending receipts JSON")
        return [item for item in pending if isinstance(item, dict)]

    def ready(self) -> dict[str, Any]:
        output = self._run(["ready"])
        try:
            result = json.loads(output)
        except ValueError as exc:
            raise RuntimeError("fm-inbox returned invalid ready JSON") from exc
        if not isinstance(result, dict):
            raise RuntimeError("fm-inbox returned invalid ready JSON")
        return result


class State:
    def __init__(self, directory: Path) -> None:
        self.directory = directory
        self.directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        os.chmod(self.directory, 0o700)
        self.path = directory / "state.json"
        self.lock_path = directory / "state.lock"
        self.choices_path = directory / "pending-choices.json"
        self.choices_lock_path = directory / "pending-choices.lock"
        self.data: dict[str, Any] = self._load(
            self.path, {"offset": 0, "receipt_cursor": "", "telegram_note_ids": []})
        # v1 stored choices beside the polling state.  Move them to a file which
        # notify can update without a long-running bridge overwriting it later.
        legacy_choices = self.data.pop("pending_choices", None)
        self._saved_data = copy.deepcopy(self.data)
        if isinstance(legacy_choices, dict):
            if not self.choices_path.exists():
                self.update_choices(lambda choices: choices.update(legacy_choices))
            # Arrange for the next ordinary state save to remove the old copy.
            self._saved_data["pending_choices"] = legacy_choices

    @staticmethod
    def _load(path: Path, fallback: dict[str, Any]) -> dict[str, Any]:
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
            return loaded if isinstance(loaded, dict) else dict(fallback)
        except (FileNotFoundError, ValueError):
            return dict(fallback)

    @staticmethod
    def _write(path: Path, data: dict[str, Any]) -> None:
        # A unique temporary name matters because notify and run are separate
        # processes.  os.replace makes every completed write all-or-nothing.
        descriptor, temporary_name = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
        temporary = Path(temporary_name)
        try:
            os.fchmod(descriptor, 0o600)
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                json.dump(data, handle, separators=(",", ":"))
                handle.flush()
                os.fsync(handle.fileno())
            temporary.replace(path)
        finally:
            try:
                temporary.unlink()
            except FileNotFoundError:
                pass

    @staticmethod
    def _changed_keys(before: dict[str, Any], after: dict[str, Any]) -> set[str]:
        return {key for key in set(before) | set(after) if before.get(key) != after.get(key)}

    def _locked(self, path: Path) -> Any:
        descriptor = os.open(path, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
        handle = os.fdopen(descriptor, "r+")

        class Lock:
            def __enter__(_self: Any) -> None:
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX)

            def __exit__(_self: Any, *_args: Any) -> None:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
                handle.close()

        return Lock()

    def save(self) -> None:
        # Do not write a stale in-memory snapshot over another process's keys.
        # This is especially important because notify and run both use State.
        changed = self._changed_keys(self._saved_data, self.data)
        with self._locked(self.lock_path):
            current = self._load(self.path, {})
            for key in changed:
                if key in self.data:
                    current[key] = copy.deepcopy(self.data[key])
                else:
                    current.pop(key, None)
            self._write(self.path, current)
        self.data = current
        self._saved_data = copy.deepcopy(current)

    def choices(self) -> dict[str, Any]:
        """Read choices fresh: a notify process may have just created one."""
        with self._locked(self.choices_lock_path):
            return self._load(self.choices_path, {})

    def update_choices(self, change: Callable[[dict[str, Any]], Any]) -> Any:
        """Atomically apply a change to the private pending-choice store."""
        with self._locked(self.choices_lock_path):
            choices = self._load(self.choices_path, {})
            result = change(choices)
            self._write(self.choices_path, choices)
            return result


class Episode:
    """Remember one unhealthy period without repeating its alert every poll."""
    def __init__(self, state: Optional[State] = None, key: Optional[str] = None) -> None:
        self.state, self.key = state, key
        self.active = bool(state.data.get(key, False)) if state and key else False

    def update(self, unhealthy: bool) -> int:
        if unhealthy == self.active:
            return 0
        self.active = unhealthy
        if self.state and self.key:
            self.state.data[self.key] = unhealthy
            self.state.save()
        return 1 if unhealthy else -1


def _note_time(note: dict[str, Any]) -> Optional[float]:
    value = note.get("at", note.get("created_at"))
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return float(value)
    if not isinstance(value, str):
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc).timestamp()
    except ValueError:
        return None


def _watcher_is_down(status: str, ready: dict[str, Any]) -> bool:
    """Use the durable signals published by fm-inbox, never Firstmate state files."""
    text = status.lower()
    if "watcher still down" in text or re.search(r"\bwatcher\b[^\n]{0,80}\bdown\b", text):
        return True
    wake_consumer = ready.get("wake_consumer")
    if isinstance(wake_consumer, dict) and str(wake_consumer.get("state", "")).lower() == "down":
        return True
    return ready.get("can_receive") is False


class MainStallCheck:
    def __init__(self, inbox: Any, threshold: float, clock: Callable[[], float] = time.time,
                 state: Optional[State] = None) -> None:
        self.inbox, self.threshold, self.clock = inbox, threshold, clock
        self.episode = Episode(state, "main_stall_active")

    def poll(self) -> tuple[int, Optional[str]]:
        pending = self.inbox.pending()
        ready, status = self.inbox.ready(), self.inbox.status()
        oldest = min((item for item in (_note_time(note) for note in pending) if item is not None),
                     default=None)
        age = self.clock() - oldest if oldest is not None else 0
        waiting = oldest is not None and age >= self.threshold
        watcher_down = _watcher_is_down(status, ready)
        change = self.episode.update(waiting or watcher_down)
        if not change:
            return 0, None
        if change < 0:
            return change, "메인 응답 복구됨\n• 처리 대기 메모와 watcher 상태가 정상입니다."
        details: list[str] = []
        if waiting:
            details.append("처리되지 않은 캡틴 메모가 %d분째 대기 중입니다." % max(1, age // 60))
        if watcher_down:
            details.append("Firstmate watcher가 꺼져 있습니다.")
        hint = "Firstmate와 watcher를 확인해 주세요." if watcher_down else "Firstmate 메인을 확인해 주세요."
        return change, "메인 응답 없음\n• " + "\n• ".join(details + [hint])


@dataclass(frozen=True)
class ProbeResult:
    state: str


AUTH_FAILURE = re.compile(r"\b(?:login|log in|auth(?:entication)?)\b", re.IGNORECASE)
LOGGED_OUT = re.compile(r"logged[_ ]?in[^a-z]{0,20}false|not\s+logged\s+in", re.IGNORECASE)


def classify_probe(returncode: int, output: str, timed_out: bool = False,
                   auth_status: str = "", auth_command_failure: bool = False) -> ProbeResult:
    if timed_out:
        return ProbeResult("hang")
    if LOGGED_OUT.search(output) or LOGGED_OUT.search(auth_status):
        return ProbeResult("auth")
    if returncode == 0:
        return ProbeResult("ok")
    if auth_command_failure or AUTH_FAILURE.search(output):
        return ProbeResult("auth")
    return ProbeResult("error")


def run_claude_probe(command: list[str], timeout: float,
                     auth_command: list[str]) -> ProbeResult:
    """Run a bounded no-tool probe and distinguish a timeout from an auth failure."""
    try:
        result = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return classify_probe(1, "", timed_out=True)
    except OSError:
        return ProbeResult("error")
    output = (result.stdout or "") + "\n" + (result.stderr or "")
    auth_status = ""
    if result.returncode:
        try:
            auth = subprocess.run(auth_command, text=True, stdout=subprocess.PIPE,
                                  stderr=subprocess.PIPE, timeout=min(timeout, 10), check=False)
            auth_status = (auth.stdout or "") + "\n" + (auth.stderr or "")
        except (OSError, subprocess.TimeoutExpired):
            pass
    return classify_probe(result.returncode, output, auth_status=auth_status,
                          auth_command_failure=bool(result.returncode and command == auth_command))


class ClaudeProbeCheck:
    """Start probes off-loop, so a stuck CLI cannot pause Telegram polling."""
    def __init__(self, command: list[str], auth_command: list[str], interval: float, timeout: float,
                 clock: Callable[[], float] = time.monotonic, state: Optional[State] = None) -> None:
        self.command, self.auth_command = command, auth_command
        self.interval, self.timeout, self.clock = interval, timeout, clock
        self.episode, self.next_at = Episode(state, "claude_probe_active"), 0.0
        self._thread: Optional[threading.Thread] = None
        self._result: Optional[ProbeResult] = None

    def poll(self, send: Callable[[str], None]) -> None:
        now = self.clock()
        if self._thread and not self._thread.is_alive():
            result, self._thread, self._result = self._result, None, None
            self.next_at = now + self.interval
            if result:
                change = self.episode.update(result.state != "ok")
                if change > 0:
                    alerts = {"auth": "로그인 필요\n• Claude 로그인이 확인되지 않습니다.\n• `claude auth login`을 실행해 주세요.",
                              "hang": "Claude 멈춤\n• Claude 점검이 제한 시간 안에 끝나지 않았습니다.\n• Claude를 다시 열고 로그인 상태를 확인해 주세요.",
                              "error": "Claude 점검 실패\n• Claude probe가 실패했습니다.\n• `claude auth status`를 확인해 주세요."}
                    send(alerts[result.state])
                elif change < 0:
                    send("Claude 점검 복구됨\n• Claude probe가 다시 정상 응답합니다.")
        if self._thread is None and now >= self.next_at:
            self._thread = threading.Thread(target=self._run, daemon=True, name="fm-telegram-claude-probe")
            self._thread.start()

    def _run(self) -> None:
        self._result = run_claude_probe(self.command, self.timeout, self.auth_command)


